// Generates the 2D fallback volleyball (src/components/ball/volleyballSvgData.js)
// from the exact panel layout the 3D shader uses (src/lib/volleyballPattern.js).
//
//   npm run ball:svg
//
// Every panel outline is rotated into a pleasant viewing angle and projected
// orthographically. Points that end up on the back of the ball are pushed out
// onto the silhouette circle, which turns each partly visible panel into
// exactly its visible part; fully hidden panels are dropped.
import { writeFile } from "node:fs/promises";
import { allPanels, BALL_COLORS } from "../src/lib/volleyballPattern.js";

const VIEW = 200;
const R = 96; // leaves room for the rim stroke inside the 200x200 viewBox
const C = VIEW / 2;
// viewing angle (radians): yaw around Y, then pitch around X
const YAW = 0.62;
const PITCH = -0.5;
const SAMPLES = 12;

function rotate([x, y, z]) {
  const cy = Math.cos(YAW), sy = Math.sin(YAW);
  const x1 = x * cy + z * sy;
  const z1 = -x * sy + z * cy;
  const cp = Math.cos(PITCH), sp = Math.sin(PITCH);
  const y2 = y * cp - z1 * sp;
  const z2 = y * sp + z1 * cp;
  return [x1, y2, z2];
}

const fmt = (n) => (Math.round(n * 10) / 10).toString();
const toSvg = ([x, y]) => `${fmt(C + x * R)} ${fmt(C - y * R)}`;

function onLimb([x, y]) {
  const len = Math.hypot(x, y) || 1;
  return [x / len, y / len];
}

const panels = [];
const seams = [];

for (const panel of allPanels(SAMPLES)) {
  const pts = panel.outline.map(rotate);
  if (pts.every((p) => p[2] <= 0)) continue;

  const projected = pts.map((p) => (p[2] > 0 ? [p[0], p[1]] : onLimb(p)));
  panels.push({ d: "M" + projected.map(toSvg).join("L") + "Z", fill: panel.color });

  // seams: only the visible runs of the outline (closing the loop as well)
  let run = [];
  const flush = () => {
    if (run.length > 1) seams.push("M" + run.map(toSvg).join("L"));
    run = [];
  };
  for (let i = 0; i <= pts.length; i++) {
    const p = pts[i % pts.length];
    if (p[2] > 0) run.push([p[0], p[1]]);
    else flush();
  }
  flush();
}

const file = `// GENERATED by scripts/generate-ball-svg.mjs — do not edit by hand.
// Same 18-panel layout as the 3D shader, seen from a fixed angle.
export const BALL_SVG = ${JSON.stringify(
  { view: VIEW, center: C, radius: R, seam: BALL_COLORS.seam, base: BALL_COLORS.cream, panels, seams: seams.join("") },
  null,
  0
)};
`;

const out = new URL("../src/components/ball/volleyballSvgData.js", import.meta.url);
await writeFile(out, file);
console.log(`ball svg: ${panels.length} visible panels, ${(file.length / 1024).toFixed(1)} KB -> ${out.pathname}`);
